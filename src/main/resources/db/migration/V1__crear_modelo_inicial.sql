    CONSTRAINT fk_detalle_despacho_despacho
        FOREIGN KEY (id_despacho) REFERENCES despacho (id_despacho)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_detalle_despacho_detalle_venta
        FOREIGN KEY (id_detalle_venta) REFERENCES detalle_venta (id_detalle_venta)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_despacho_lote
        FOREIGN KEY (id_lote) REFERENCES lote (id_lote)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_despacho_almacen
        FOREIGN KEY (id_almacen) REFERENCES almacen (id_almacen)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE detalle_recepcion (
    id_detalle_recepcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recepcion BIGINT NOT NULL,
    id_detalle_compra BIGINT NOT NULL,
    cantidad BIGINT NOT NULL CHECK (cantidad > 0),
    id_almacen BIGINT NOT NULL,
    CONSTRAINT fk_detalle_recepcion_recepcion
        FOREIGN KEY (id_recepcion) REFERENCES recepcion (id_recepcion)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_detalle_recepcion_detalle_compra
        FOREIGN KEY (id_detalle_compra) REFERENCES detalle_compra (id_detalle_compra)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_recepcion_almacen
        FOREIGN KEY (id_almacen) REFERENCES almacen (id_almacen)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE recepcion_compra (
    id_recepcion BIGINT NOT NULL,
    id_compra BIGINT NOT NULL,
    PRIMARY KEY (id_recepcion, id_compra),
    CONSTRAINT fk_recepcion_compra_recepcion
