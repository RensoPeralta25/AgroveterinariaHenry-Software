-- Nomina
CREATE TABLE nomina (
    id_nomina BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado BIGINT NOT NULL,
    fecha_emision DATE NOT NULL,
    periodo VARCHAR(20) NOT NULL CHECK (periodo IN ('MES', 'QUINCENA')),
    total_devengado DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (total_devengado >= 0),
    total_deducciones DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (total_deducciones >= 0),
    CONSTRAINT fk_nomina_empleado
        FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE detalle_nomina (
    id_detalle_nomina BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nomina BIGINT NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    tipo VARCHAR(40) NOT NULL CHECK (tipo IN (
        'SALARIO_BASE',
        'HORAS_EXTRAS',
        'COMISIONES',
        'BONIFICACIONES',
        'PAGO_VACACIONES',
        'SUELDO_13',
        'DIETAS_Y_VIATICOS',
        'SEGURO_FAMILIAR_SALUD',
        'FONDO_PENSIONES',
        'IMPUESTO_RENTA',
        'ANTICIPO_SALARIO',
        'PRESTAMO_EMPRESA',
        'AUSENCIAS_NO_PAGADAS',
        'EMBARGO_SALARIAL',
        'OTRAS_DEDUCCIONES'
    )),
    monto DECIMAL(12,2) NOT NULL CHECK (monto >= 0),
    cantidad DECIMAL(12,2) NOT NULL DEFAULT 1 CHECK (cantidad >= 0),
    CONSTRAINT fk_detalle_nomina_nomina
        FOREIGN KEY (id_nomina) REFERENCES nomina (id_nomina)
        ON UPDATE CASCADE ON DELETE CASCADE
);

