CREATE TABLE gasto_transporte (
    id_gasto_transporte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transporte BIGINT NOT NULL,
    id_gasto BIGINT NOT NULL,
    CONSTRAINT fk_gasto_transporte_transporte
        FOREIGN KEY (id_transporte) REFERENCES transporte (id_transporte)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_gasto_transporte_gasto
        FOREIGN KEY (id_gasto) REFERENCES gasto_operativo (id_gasto)
        ON UPDATE CASCADE ON DELETE RESTRICT
